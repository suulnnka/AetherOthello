/* ============================================================
 * 难度分档(zig/wasm 通道)
 *
 * 放在独立文件里,是因为**两边都要用**:UI 要 name 建下拉,Worker 要
 * depth/end/budget 调引擎。写两份必然漂移(改档位只改了一边,界面显示
 * 「高级」而引擎跑的还是中级 —— 象棋那边就踩过一次)。
 *
 * 难度按**节点预算**而不是墙钟时间:设备无关、可复现、浏览器探针能断言。
 * 深度只当上限 —— 预算先用满时实际达不到标称深度,别拿它当卖点。
 *
 * end = 进入完全求解的空格阈值。实测(wasm,ReleaseFast,自对弈中段局面):
 *   ≤10 空  ~4 ms · 12 空 ~20 ms · 14 空 ~70 ms · 16 空 0.17–0.95 s
 *   18 空 4–25 s(不设上限的那个局面 53M 节点)→ **阈值封顶 16**,
 *   再往上 UI 就会卡住十几秒,用户只会以为程序死了。
 * ============================================================ */

/** budget 单位是节点数(0 = 不限);depth = 0 表示纯贪心不搜索 */
export const LEVELS = [
  { name: '初级', desc: '贪心选点(位置权重 + 翻子数),不搜索', depth: 0, end: 0, budget: 0 },
  { name: '中级', desc: 'PVS 4 层(≤20 万节点) · 残局 8 空完全求解', depth: 4, end: 8, budget: 200_000 },
  { name: '高级', desc: 'PVS 10 层(≤200 万节点) · 残局 14 空完全求解', depth: 10, end: 14, budget: 2_000_000 },
  { name: '大师', desc: 'PVS 16 层(≤1200 万节点) · 残局 16 空完全求解', depth: 16, end: 16, budget: 12_000_000 },
];
