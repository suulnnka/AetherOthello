/* ============================================================
 * 难度分档 —— **两个分支共用同一份,必须逐字节一致**
 *
 * 为什么单独成文件、且两边都不许各改各的:UI 要 name 建下拉,Worker 要
 * depth/end/budget 调引擎。写两份必然漂移(改档位只改了一边,界面显示「高级」
 * 而引擎跑的还是中级 —— 象棋那边就踩过一次)。main(JS 参照实现)与 zig
 * (Zig + wasm)共用这一张表,所以「同一个档位」在两个引擎里指的是同一组参数,
 * 输出才可比。契约见 docs/WORKER-PROTOCOL.md,对比跑 tools/compare-branches.mjs。
 *
 * 难度按**节点预算**而不是墙钟时间:设备无关、可复现、浏览器探针能断言。
 * depth 只当上限 —— 预算先用满时实际达不到标称深度,别拿它当卖点。
 *
 * end = 进入完全求解的空格阈值。阈值是按 wasm 通道实测定的(zig 分支):
 *   ≤10 空 ~4 ms · 12 空 ~20 ms · 14 空 ~70 ms · 16 空 0.17–0.95 s
 *   18 空 4–25 s(不设上限的那个局面 53M 节点)→ **封顶 16**,
 *   再往上 UI 就会卡住十几秒,用户只会以为程序死了。
 * JS 通道吃同一张表:它的节点速度约为 wasm 通道的一半,同阈值的耗时会明显更长,
 * 两边实测差异见 tools/compare-branches.mjs 的输出(那边的耗时列就是为此留的)。
 * ============================================================ */

